"""Numbers for the appendix 'Better homodyne reconstruction'.

Reads the paired Q-W results of the better-FBP W networks (results_full.json of the better-FBP run,
produced by qmi/analiza2.py: one entry per cell, e.g. 'loss_0_N100', with the variants
'paper_W36_5seeds', 'kak2', 'hann2') and writes paper/results/numbers_fbp2.tex with \\RES keys
fbp2_<variant>_<cell>_<N>_{dQW,dQW_ci,accW,nW}. Without an input file it writes placeholders
so that the appendix skeleton compiles.
  python paper/scripts/fbp2_table.py [path/to/results_full.json [path/to/fbp_err.json]]
fbp_err.json gives the median relative L2 error of the FBP variants at N=infinity (keys fbp2_err_*)."""
import json, sys, os
HERE = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(HERE, "..", "results", "numbers_fbp2.tex")
CELLS = {"loss_0": "clean", "loss_50": "loss50", "loss_80": "loss80", "dephase_20": "deph20"}
NS = {"N100": "N100", "N1000": "N1000", "N10000": "N10000"}
VARS = {"paper_W36_5seeds": "paper", "kak2": "kak2", "hann2": "hann2", "kak2_vs_paperW_sameseeds": "oldsame_kak2", "hann2_vs_paperW_sameseeds": "oldsame_hann2"}
def fmt(x): return ("%.1f" % x).replace("-", "$-$")
def main():
    d = json.load(open(sys.argv[1])) if len(sys.argv) > 1 and os.path.exists(sys.argv[1]) else None
    lines = ["% generated by paper/scripts/fbp2_table.py; do not edit by hand"]
    for ck, cn in CELLS.items():
        for nk, nn in NS.items():
            for vk, vn in VARS.items():
                key = "fbp2_%s_%s_%s" % (vn, cn, nn)
                if d is None:
                    vals = {"dQW": "\\textcolor{red}{TBD}", "dQW_ci": "\\textcolor{red}{TBD}", "accW": "\\textcolor{red}{TBD}", "nW": "\\textcolor{red}{TBD}"}
                else:
                    r = d.get("%s_%s" % (ck, nk), {}).get(vk)
                    if r is None: continue
                    vals = {"dQW": fmt(r["diff"]), "dQW_ci": "[%s, %s]" % (fmt(r["lo"]), fmt(r["hi"])), "accW": fmt(r["accW"]), "nW": str(int(r["nW"]))}
                for k, v in vals.items(): lines.append("\\expandafter\\def\\csname res@%s_%s\\endcsname{%s}" % (key, k, v))
    e = json.load(open(sys.argv[2])) if len(sys.argv) > 2 and os.path.exists(sys.argv[2]) else None
    for key, vk in (("paper", "old_o1_ramp"), ("kak2", "new_o2_kak"), ("hann2", "o2_kak_hann")):
        v = ("%.3f" % e["by_variant"][vk]["median"]) if e else "\\textcolor{red}{TBD}"
        lines.append("\\expandafter\\def\\csname res@fbp2_err_%s\\endcsname{%s}" % (key, v))
    nw = None
    if d is not None:
        nw = d.get("dephase_20_N100", {}).get("hann2", {}).get("nW")
    lines.append("\\expandafter\\def\\csname res@fbp2_nW_hann2\\endcsname{%s}" % (str(int(nw)) if nw else "\\textcolor{red}{TBD}"))
    open(OUT, "w").write("\n".join(lines) + "\n"); print("wrote", OUT, len(lines) - 1, "definitions", "(placeholders)" if d is None else "")
if __name__ == "__main__": main()
