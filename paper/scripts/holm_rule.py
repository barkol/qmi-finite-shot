#!/usr/bin/env python3
"""Holm-adjusted p values of the paired differences Q-W and Q-S of figure `rule`.
Czyta results/ci.json i results/ci_ahm.json (pola mean, se_states, se_seeds, df z qmi/x8/pary.py) i pisze results/numbers_holm.tex.
p komorki = najmniejszy poziom a, przy ktorym przedzial hypot(z_{1-a/2} se_states, t_{1-a/2,df} se_seeds) wokol mean wyklucza 0
(ten sam przedzial co w tekscie). Rodzina: 24 komorki (2 zbiory x N in {1e2,1e3,1e4} x 4 warunki) osobno dla Q-W i dla Q-S."""
import json, math, os, re, sys
from scipy import stats, optimize
R = sys.argv[1] if len(sys.argv) > 1 else "results"
def pval(c):
    m = abs(c["mean"]); se1, se2, df = c["se_states"], c["se_seeds"], c["df"]
    if m == 0: return 1.0
    f = lambda a: math.hypot(stats.norm.ppf(1 - a / 2) * se1, stats.t.ppf(1 - a / 2, df) * se2) - m
    return optimize.brentq(f, 1e-14, 0.999999)
def holm(ps):
    items = sorted(ps.items(), key=lambda kv: kv[1]); m = len(items); adj = {}; run = 0.0
    for i, (k, p) in enumerate(items):
        run = max(run, min(1.0, (m - i) * p)); adj[k] = run
    return adj
A = json.load(open(os.path.join(R, "ci.json"))); B = json.load(open(os.path.join(R, "ci_ahm.json")))
keys = {}
for name, suf in (("QW", "dQW"), ("QS", "dQS")):
    ps = {}
    for pre, d in (("base", A), ("ahm", B)):
        for k, c in d.items():
            if re.fullmatch(r"(ahm_)?rule_N(100|1000|10000)_[a-z0-9]+_" + suf, k) and isinstance(c, dict) and "se_states" in c:
                ps[(pre, k)] = pval(c)
    adj = holm(ps)
    keys[f"holm_ncell_{name}"] = str(len(ps))
    keys[f"holm_nsig_{name}"] = str(sum(v < 0.05 for v in adj.values()))
    keys[f"holm_nsig_base_{name}"] = str(sum(v < 0.05 for (p, k), v in adj.items() if p == "base"))
    keys[f"holm_nsig_ahm_{name}"] = str(sum(v < 0.05 for (p, k), v in adj.items() if p == "ahm"))
    if name == "QW":
        for tag in ("deph20", "loss80", "loss50", "clean"):
            keys[f"holm_p_{tag}"] = f"{adj[('base', f'rule_N100_{tag}_dQW')]:.3f}"
keys["holm_ncell"] = keys["holm_ncell_QW"]
with open(os.path.join(R, "numbers_holm.tex"), "w") as fh:
    fh.write("% generated by scripts/holm_rule.py\n")
    for k, v in sorted(keys.items()):
        fh.write("\\expandafter\\def\\csname res@%s\\endcsname{%s}\n" % (k, v))
print(keys)
