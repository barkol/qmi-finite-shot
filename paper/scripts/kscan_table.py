"""Dependence of the Wigner-network accuracy on the number of phases K (appendix app:kscan).
Reads the stored result files only; writes results/numbers_kscan.tex (keys kscan_*) and results/kscan.json.

Sources (base set): Q and W(K=36): eval_shots.json + eval_shots_s[0-9].json (5 runs);
W(K=12): eval_shots_K12_all.json (3 runs); W(K=6): eval_shots_Kscan_K6.json (3 runs).
Interval for Q-W: the construction of make_numbers.paired_diff (z for the test-state term, Welch t for the
runs, added in quadrature). Per-state outcomes of the K=6 and K=12 networks were not stored, so the test-state
term cannot be paired; we bound it by treating the errors of Q and W on a state as independent, with per-family
accuracies from the stored confusion matrices (stratified like the paired version). It is an upper bound on the
paired term, so these intervals are conservative; the paired K=36 interval of the paper is listed for comparison."""
import glob, json, os
import numpy as np
from scipy.stats import t as tdist

HERE = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(HERE, "..", "results")
CELLS = [("clean", "loss", "0"), ("loss50", "loss", "50"), ("loss80", "loss", "80"), ("deph20", "dephase", "20")]
NS = ["100", "1000", "10000"]


def load(p):
    return json.load(open(os.path.join(R, p)))


def merged(files):
    d = {}
    for f in files: d.update(load(f))
    return d


main = merged(["eval_shots.json"] + [os.path.basename(f) for f in sorted(glob.glob(os.path.join(R, "eval_shots_s[0-9].json")))])
nets = {
    "Q": [main[n] for n in sorted(main) if n.startswith("clf_Q_shots_s")],
    "W36": [main[n] for n in sorted(main) if n.startswith("clf_W_shots_s")],
    "W12": [v for n, v in sorted(load("eval_shots_K12_all.json").items()) if "shotsK12_s" in n],
    "W6": [v for n, v in sorted(load("eval_shots_Kscan_K6.json").items()) if "shotsK6_s" in n],
}
paired36 = load("ci.json")


def cell(rs, ch, N, L):
    c = [r[ch][N][L] for r in rs]
    acc = np.array([x["acc"] for x in c]); cm = np.array([x["cm"] for x in c], float)
    pf = np.array([np.diag(m) / m.sum(1) for m in cm]).mean(0)      # per-family accuracy, mean over runs
    return acc, pf, c[0]["n"]


def diff(q, w):
    (aq, pq, n), (aw, pw, _) = q, w
    nc = n / len(pq)
    se_st = np.sqrt(sum(nc * (pq[c] * (1 - pq[c]) + pw[c] * (1 - pw[c])) for c in range(len(pq)))) / n
    vq, vw = aq.var(ddof=1) / len(aq), aw.var(ddof=1) / len(aw)
    df = (vq + vw) ** 2 / (vq ** 2 / (len(aq) - 1) + vw ** 2 / (len(aw) - 1)) if vq + vw > 0 else 1e9
    D = aq.mean() - aw.mean()
    h = np.hypot(1.959964 * se_st, tdist.ppf(0.975, df) * np.sqrt(vq + vw))
    return dict(mean=100 * D, lo=100 * (D - h), hi=100 * (D + h), df=float(df))


out, keys = {}, {}
for tag, ch, L in CELLS:
    for N in NS:
        c = {k: cell(rs, ch, N, L) for k, rs in nets.items()}
        row = {f"acc_{k}": 100 * float(v[0].mean()) for k, v in c.items()}
        row.update({f"nruns_{k}": len(v[0]) for k, v in c.items()})
        for K in ("6", "12", "36"):
            row[f"dQW{K}"] = diff(c["Q"], c["W" + K])
        pk = f"rule_N{N}_{tag}_dQW"
        if pk in paired36: row["dQW36_paired_paper"] = {x: 100 * paired36[pk][x] for x in ("mean", "lo", "hi")}
        out[f"N{N}_{tag}"] = row
        for k in ("Q", "W6", "W12", "W36"):
            keys[f"kscan_N{N}_{tag}_{k}"] = f"{row['acc_' + k]:.1f}\\%"
        for K in ("6", "12", "36"):
            d = row[f"dQW{K}"]
            keys[f"kscan_N{N}_{tag}_dQW{K}"] = f"{d['mean']:.1f}"
            keys[f"kscan_N{N}_{tag}_dQW{K}_ci"] = f"\\ensuremath{{[{d['lo']:.1f},\\,{d['hi']:.1f}]}}"
for k, rs in nets.items(): keys[f"kscan_nruns_{k}"] = str(len(rs))
# fraction of the K=36 gap removed at N=100
for tag, _, _ in CELLS:
    g36, g6, g12 = (out[f"N100_{tag}"][f"dQW{K}"]["mean"] for K in ("36", "6", "12"))
    keys[f"kscan_N100_{tag}_shrink6"] = f"{100 * (1 - g6 / g36):.0f}\\%" if abs(g36) > 0.05 else "--"
    keys[f"kscan_N100_{tag}_shrink12"] = f"{100 * (1 - g12 / g36):.0f}\\%" if abs(g36) > 0.05 else "--"

with open(os.path.join(R, "numbers_kscan.tex"), "w") as f:
    f.write("% generated by scripts/kscan_table.py -- do not edit by hand\n")
    for k in sorted(keys): f.write(f"\\expandafter\\def\\csname res@{k}\\endcsname{{{keys[k]}}}\n")
json.dump(out, open(os.path.join(R, "kscan.json"), "w"), indent=1, sort_keys=True)
for k, r in out.items():
    print(k, " ".join(f"{x}={r['acc_'+x]:.1f}" for x in ("Q", "W6", "W12", "W36")),
          " ".join(f"d{K}={r['dQW'+K]['mean']:.1f}[{r['dQW'+K]['lo']:.1f},{r['dQW'+K]['hi']:.1f}]" for K in ("6", "12", "36")),
          "paper36", "%.1f" % r.get("dQW36_paired_paper", {}).get("mean", float("nan")))
