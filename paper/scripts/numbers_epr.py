#!/usr/bin/env python3
"""Writes results/numbers_epr.tex from analyses/kawasaki_epr/wyniki.json (EPR one-mode records).
Base-set networks, K=6, variant A, exp_los vs sym_term (the comparison of the text); Ahmed-set K=6 variant B, exp_blok vs sym_gauss."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "..", "analyses", "kawasaki_epr", "wyniki.json")
out = os.path.join(here, "..", "results", "numbers_epr.tex")
d = json.load(open(src))["istotnosc_w_zakresie"]
b = d["baza_K6_A|exp_los_vs_sym_term"]
bB = d["baza_K6_B|exp_los_vs_sym_term"]
a = d["ahm_K6_B|exp_blok_vs_sym_gauss"]
# the base-set statement must not depend on the variant: same test count, same rounded minimum
assert b["ntest"] == bB["ntest"] and f"{b['pmin']:.2f}" == f"{bB['pmin']:.2f}"
assert b["n_bonf"] == 0 and bB["n_bonf"] == 0
keys = {
    "epr_ntest": str(b["ntest"]),
    "epr_pmin": f"{b['pmin']:.2f}",
    "epr_ahm_ntest": str(a["ntest"]),
    "epr_ahm_nbonf": str(a["n_bonf"]),
    "epr_ahm_pmin": f"{a['pmin']:.4f}",
}
with open(out, "w") as f:
    f.write("% generated by scripts/numbers_epr.py -- do not edit by hand\n")
    for k in sorted(keys):
        f.write("\\expandafter\\def\\csname res@%s\\endcsname{%s}\n" % (k, keys[k]))
print(keys)
