r"""Makra \RES dla akapitu o MaxLik: wyniki_maxlik.json -> <paper>/results/numbers_maxlik.tex (klucze ml_*)."""
import json, os
from pathlib import Path
H = Path(__file__).resolve().parent
OUT = (Path(os.environ.get("QMI_PAPER", Path(__file__).resolve().parents[2] / "paper")) / "results") / "numbers_maxlik.tex"
D = json.loads((H / "wyniki_maxlik.json").read_text())
neg = lambda v: (v[1:] if __import__("re").fullmatch(r"-0\.0+", v) else r"\ensuremath{-}" + v[1:]) if v.startswith("-") else v
pp = lambda x: neg(f"{100 * x:.1f}")
ci = lambda c: r"\ensuremath{[" + f"{100 * c['lo']:.1f},\\,{100 * c['hi']:.1f}" + "]}"
m = {}
for s, pfx in (("base", ""), ("ahm", "ahm_")):
    for cell, v in D[s].items():
        for k, nm in (("Q-ML", "dQML"), ("S-ML", "dSML"), ("ML-W", "dMLW")):
            if k in v["diff"]:
                c = v["diff"][k]; m[f"{pfx}ml_{cell}_{nm}"] = pp(c["mean"]); m[f"{pfx}ml_{cell}_{nm}_ci"] = ci(c)
        if "ML" in v["acc"]: m[f"{pfx}ml_{cell}_acc"] = f"{100 * v['acc']['ML']:.1f}\\%"
b = D["base"]
assert b["clean_N100"]["diff"]["Q-ML"]["lo"] < 0 < b["clean_N100"]["diff"]["Q-ML"]["hi"]
assert all(b[f"{c}_N1000"]["diff"]["Q-ML"]["lo"] <= 0 <= b[f"{c}_N1000"]["diff"]["Q-ML"]["hi"] for c in ("clean", "loss50", "loss80", "deph20"))
m["ml_D"] = "40"
L = ["% generated by analyses/maxlik/numbers_maxlik.py from wyniki_maxlik.json -- do not edit by hand"] + [f"\\expandafter\\def\\csname res@{k}\\endcsname{{{v}}}" for k, v in sorted(m.items())]
OUT.write_text("\n".join(L) + "\n"); print(len(m), "kluczy")
for k in ("ml_clean_N100_dQML", "ml_deph20_N100_dQML", "ml_loss80_N100_dQML", "ml_loss80_N100_dSML", "ahm_ml_clean_N100_dQML"): print(k, m.get(k), m.get(k + "_ci"))
