r"""Makra \RES dla akapitu o Gradient-SHAP w Dyskusji: analyses/shap/out/summary.json -> <paper>/results/numbers_shap.tex (klucze shap_*).
Mediany po 7 rodzinach, stany czyste, rekordy N=100 vs wejscia dokladne, dwa przebiegi treningowe (s0, s1);
wzbogacenie obszarow W<0 (neg_enrich) sieci wytrenowanej i w pelni losowej: podzbior 70 stanow, przebieg s0 (shap_summary.py, kaskada)."""
import json, os, statistics
from pathlib import Path
A = Path(__file__).resolve().parent
OUT = (Path(os.environ.get("QMI_PAPER", Path(__file__).resolve().parents[2] / "paper")) / "results") / "numbers_shap.tex"
S = json.loads((A / "out" / "summary.json").read_text())
K = {}
for s in ("s0", "s1"):
    for kind, tag in (("rec", "rec"), ("ex", "ex")):
        v = list(S["attr"][f"clean|W_{s}|{kind}|other"]["out_support"].values())
        K[f"shap_out_W_{tag}_{s}"] = f"{statistics.median(v):.2f}"
e = S["sanity"]["W|rec"]["neg_enrich"]
assert S["cascade"][0] == "trained" and S["cascade"][-1] == "features.0", S["cascade"]
K["shap_enrich_W_trained"] = f"{e[0]:.1f}"; K["shap_enrich_W_random"] = f"{e[-1]:.1f}"; K["shap_enrich_ratio"] = f"{e[0] / e[-1]:.1f}"
with open(OUT, "w") as fh:
    fh.write("% generated by analyses/shap/numbers_shap.py -- do not edit by hand\n")
    for k, v in sorted(K.items()):
        fh.write("\\expandafter\\def\\csname res@%s\\endcsname{%s}\n" % (k, v))
print(K)
