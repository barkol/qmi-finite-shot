"""Makra do akapitu o rekordach PSS Kawasaki+ 2024 (bez sieci Ahmeda K=6, ktore nie wchodza do pracy) oraz test na poziomie
rekordu dla Konno -> numbers_kawasaki.tex. Zrodla: out/summary.json (agg.py), out_konno/konno_rek.json (konno_rek.py).
Stop na pierwszej niespojnosci (asercje). Nie nadpisuje pliku, ktorego nie wygenerowal ten skrypt.
  python -I analyses/kawasaki/numbers_kawasaki.py [--out PLIK]"""
import argparse, json, os, sys
from pathlib import Path

A = Path(os.path.dirname(os.path.abspath(__file__)))
DEF = (Path(os.environ.get("QMI_PAPER", Path(__file__).resolve().parents[2] / "paper")) / "results") / "numbers_kawasaki.tex"
HEAD = "% generated by analyses/kawasaki/numbers_kawasaki.py -- do not edit by hand\n"
PUMP = {1: "01mW_00dB", 3: "03mW_00dB", 10: "10mW_00dB", 25: "25mW_00dB"}
LOSS = {0: "01mW_00dB_2", 1: "01mW_01dB_2", 2: "01mW_02dB_2", 5: "01mW_05dB_2", 10: "01mW_10dB_2", 15: "01mW_15dB_2", 20: "01mW_20dB_2"}
PAPER_W = {3: -0.097, 10: -0.088, 25: -0.066}            # arXiv:2402.17408, hbar=1
GAUSS = {"coherent", "thermal", "vacuum"}; SETS = ("baza", "gkpx")
K = {}


def num(x, d):
    s = f"{x:.{d}f}"; s = s[1:] if s.startswith("-") and float(s) == 0 else s; return (r"\ensuremath{-}" + s[1:]) if s.startswith("-") else s


def put(k, v):
    assert k not in K, k; K["kawa_" + k] = v


ap = argparse.ArgumentParser(); ap.add_argument("--out", default=str(DEF)); a = ap.parse_args()
S = json.load(open(A / "out/summary.json")); P = S["pliki"]; T = S["testy"]
assert len(P) == 11, len(P)

# zdanie 1: dane
nev = {t: None for t in P}
for t in P: assert P[t]["ml"]["nboot"] >= 20, t
put("nev", "5000"); put("nphase", "6"); put("npump", str(len(PUMP))); put("lossmax", str(max(LOSS)))
put("nset", str(len(P)))

# zdanie 2: ujemnosc wobec pracy (min W z MaxLik; zgodnosc w granicach 2 sigma bootstrapu + niepewnosci pracy)
for p, pw in PAPER_W.items():
    m = P[PUMP[p]]["ml"]; assert m["sgn"] == 1 and abs(m["Wmin"] - pw) < 2 * (m["boot_sd"]["Wmin"] + 0.006), (p, m["Wmin"], pw)
    assert abs(P[PUMP[p]]["paper_W0"][0] - pw) < 1e-9
    put(f"wmin_{p}mW", num(m["Wmin"], 3)); put(f"wpap_{p}mW", num(pw, 3)); put(f"wmin_{p}mW_sd", f"{m['boot_sd']['Wmin']:.3f}")
assert max(P[t]["ml"]["tvd_max"] for t in P) < 0.06

# zdanie 3: testy exp wobec sym (bazowe + gkpx, bez Ahmeda): test na poziomie rekordu i dokladny test blokow
rek = [p for nm in SETS for t in P for N in ("100", "1000", "10000") for p in P[t][f"klasyf_{nm}"][N]["rek_p_sieci"]]
blk = [p for nm in SETS for t in P for N in ("100", "1000", "10000") for p in P[t][f"klasyf_{nm}"][N]["p_blok_exact"]]
assert len(rek) == len(blk) == 2 * 11 * 3 * 3
for nm in SETS: assert T[nm]["n_rek_sieci"] == 99 and T[nm]["n_blok_exact"] == 99
put("rek_nper", "99"); put("rek_n", str(len(rek))); put("rek_pmin", f"{min(rek):.2f}"); put("rek_pmin_bonf", f"{min(1, min(rek) * len(rek)):.2f}")
put("rek_nsig", str(sum(p < 0.05 for p in rek))); put("rek_B", str(P[PUMP[1]]["klasyf_baza"]["100"]["rek_B"]))
put("blok_n", str(len(blk))); put("blok_pmin", f"{min(blk):.2f}"); put("blok_pmin_bonf", f"{min(1, min(blk) * len(blk)):.2f}"); put("blok_nsig", str(sum(p < 0.05 for p in blk)))
assert min(1, min(rek) * len(rek)) > 0.05 and min(1, min(blk) * len(blk)) > 0.05
full = [p for nm in SETS for t in P for p in P[t][f"klasyf_{nm}"]["0"]["p_full"]]; put("full_pmin", f"{min(full):.2f}"); assert min(full) > 0.05

# zdanie 4: klasy sieci bazowych przy 0 dB, <n>
def dom(t, nm, N):
    f = P[t][f"klasyf_{nm}"][N]["frac"]["exp_los"]; return max(f, key=f.get), f[max(f, key=f.get)]
for p, want in ((1, "fock"), (3, "fock"), (10, "cat"), (25, "cat")):
    for N in ("1000", "10000"): assert dom(PUMP[p], "baza", N)[0] == want, (p, N, dom(PUMP[p], "baza", N))
put("cat25_frac_N1000", f"{100 * dom(PUMP[25], 'baza', '1000')[1]:.0f}" + r"\%")
nb = [P[PUMP[p]]["ml"]["nbar"] for p in PUMP]; assert max(nb) < 2.0          # ponizej zakresu treningowego <n> in {2..5}
put("nbar_min", f"{min(nb):.1f}"); put("nbar_max", f"{max(nb):.1f}")
put("sqdb_min", f"{P[PUMP[1]]['pss']['sqdb']:.1f}"); put("sqdb_max", f"{P[PUMP[25]]['pss']['sqdb']:.1f}")
assert P[PUMP[1]]["pss"]["sqdb"] < P[PUMP[25]]["pss"]["sqdb"]

# zdanie 5: strata - ujemnosc W i brak rodziny gaussowskiej przy N>=1e3
w = {d: P[t]["ml"] for d, t in LOSS.items()}
assert all(w[d]["W0"] + 3 * w[d]["boot_sd"]["W0"] < 0 for d in (0, 1, 2, 5, 10)) and all(w[d]["W0"] > 0 for d in (15, 20))
put("loss_neg_last", "10"); put("loss_pos_first", "15")
put("w0_15dB_sd", "%.3f" % w[15]["boot_sd"]["W0"]); put("wmin_15dB", num(w[15]["Wmin"], 3)); put("wmin_20dB", num(w[20]["Wmin"], 3))
put("w0_10dB", num(w[10]["W0"], 3)); put("w0_15dB", num(w[15]["W0"], 3)); put("w0_20dB", num(w[20]["W0"], 3))
for nm in SETS:
    for t in LOSS.values():
        for N in ("1000", "10000"): assert dom(t, nm, N)[0] not in GAUSS, (nm, t, N)
        assert not (set(P[t][f"klasyf_{nm}"]["0"]["full_class"]) & GAUSS), (nm, t)

# Konno: test na poziomie rekordu i dokladny test blokow (konno_rek.py)
R = json.load(open(A / "out_konno/konno_rek.json"))
for nm, tg in (("baza", "base"), ("gkpx", "gkpx")):
    r = R[nm]; put(f"konno_{tg}_rek_n", str(r["rek_n"])); put(f"konno_{tg}_rek_pmin", f"{r['rek_pmin']:.2f}")
    put(f"konno_{tg}_rek_pmin_bonf", f"{min(1, r['rek_pmin'] * r['rek_n']):.2f}"); put(f"konno_{tg}_blokx_pmin", f"{r['exact_blok_pmin']:.2f}")
    put(f"konno_{tg}_blokx_n", str(r["exact_blok_n"]))
    put(f"konno_{tg}_naive_pmin", f"{r['naive_los_pmin']:.2f}"); put(f"konno_{tg}_naive_blok_pmin", f"{r['naive_blok_pmin']:.2f}")
    assert min(1, r["rek_pmin"] * r["rek_n"]) > 0.05 and r["exact_blok_pmin"] * r["exact_blok_n"] > 0.05
assert f"{R['baza']['naive_los_pmin']:.2f}" == "0.09" and f"{R['baza']['naive_blok_pmin']:.2f}" == "0.31"      # odtwarza numbers_konno.tex

out = Path(a.out)
if out.exists() and not open(out).readline() == HEAD: sys.exit(f"BLAD: {out} istnieje i nie pochodzi z tego skryptu")
tmp = str(out) + ".tmp"
with open(tmp, "w") as f:
    f.write(HEAD)
    for k in sorted(K): f.write(f"\\expandafter\\def\\csname res@{k}\\endcsname{{{K[k]}}}\n")
os.replace(tmp, out); print(f"{len(K)} kluczy -> {out}")
for k in sorted(K): print(f"  {k} = {K[k]}")
