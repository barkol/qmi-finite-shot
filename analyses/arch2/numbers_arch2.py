r"""Makra \RES dla podrozdzialu o drugiej architekturze: wyniki.json -> <paper>/results/numbers_arch2.tex."""
import json, os
from pathlib import Path
H = Path(__file__).resolve().parent
OUT = (Path(os.environ.get("QMI_PAPER", Path(__file__).resolve().parents[2] / "paper")) / "results") / "numbers_arch2.tex"
C = json.loads((H / "wyniki.json").read_text())["cells"]
conds = ("clean", "loss50", "loss80", "deph20"); Ns = (100, 1000, 10000)
assert all(f"{c}_N{N}" in C for c in conds for N in Ns), "brak komorek"
agree = sum(C[f"{c}_N{N}"]["r18"]["leaf_QW"] == C[f"{c}_N{N}"]["v2"]["leaf_QW"] for c in conds for N in Ns)
d100 = [100 * C[f"{c}_N100"]["r18"]["dQW"]["mean"] for c in conds]
lo100 = [100 * C[f"{c}_N100"]["r18"]["dQW"]["lo"] for c in conds]
qs100 = [100 * C[f"{c}_N100"]["r18"]["dQS"]["mean"] for c in conds]
qsin = all(C[f"{c}_N100"]["r18"]["dQS"]["lo"] < 0 < C[f"{c}_N100"]["r18"]["dQS"]["hi"] for c in conds)
sig_hi = [C[f"{c}_N{N}"]["r18"]["dQW"] for c in conds for N in (1000, 10000)]
nosig = all(x["lo"] <= 0 <= x["hi"] for x in sig_hi)   # rowne 0 przy 100% w obu (lo = hi = 0)
drop = [100 * (C[f"{c}_N100"]["v2"]["acc"][r]["mean"] - C[f"{c}_N100"]["r18"]["acc"][r]["mean"]) for c in conds for r in ("Q", "W")]
assert agree == 12 and min(lo100) > 0 and nosig and qsin, (agree, lo100, nosig, qsin)
r = lambda xs: f"{min(xs):.1f}\\mbox{{--}}{max(xs):.1f}"
m = {"r18_agree": str(agree), "r18_dQW_N100": r(d100), "r18_dQS_N100": r(qs100), "r18_drop_N100": r(drop),
     "r18_nseeds": str(C["clean_N100"]["r18"]["acc"]["Q"]["k"])}
L = ["% generated by analyses/arch2/numbers_arch2.py from wyniki.json -- do not edit by hand"] + [f"\\expandafter\\def\\csname res@{k}\\endcsname{{{v}}}" for k, v in m.items()]
OUT.write_text("\n".join(L) + "\n"); print("\n".join(L))
