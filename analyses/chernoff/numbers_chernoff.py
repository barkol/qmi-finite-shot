r"""Makra \RES dla akapitu o wykladnikach Chernoffa: out/podsumowanie_<TAG>.json -> <paper>/results/numbers_chernoff.tex.
python analyses/chernoff/numbers_chernoff.py [TAG]   (TAG domyslnie M24)"""
import json, os, sys
from pathlib import Path
H = Path(__file__).resolve().parent; TAG = sys.argv[1] if len(sys.argv) > 1 else "M24"
OUT = (Path(os.environ.get("QMI_PAPER", Path(__file__).resolve().parents[2] / "paper")) / "results") / "numbers_chernoff.tex"
d = json.loads((H / "out" / f"podsumowanie_{TAG}.json").read_text())
assert set(d) == {"eqn", "ahm"} and all(len(v) == 4 for v in d.values()), "brak komorek"
rng = lambda xs, nd=2: f"{min(xs):.{nd}f}\\mbox{{--}}{max(xs):.{nd}f}"   # \mbox, bo makra stoja tez w trybie matematycznym
R = lambda c: [d[f][c]["ratio_WQ_med"] for f in d]
allr = [r["ratio_WQ_med"] for f in d for r in d[f].values()]
eff = [r[k] for f in d for r in d[f].values() for k in ("effQ_med", "effW_med")]
coh = [d[f]["clean0"]["per_class"]["coherent"] for f in d]
m = {"ch_M": TAG[1:], "ch_K": "36",
     "ch_ratio_clean": rng(R("clean0")), "ch_ratio_deph20": rng(R("dephase20")), "ch_ratio_loss": rng(R("loss50") + R("loss80")),
     "ch_extra_max": f"{round(100 * (max(allr) - 1)):d}\\%", "ch_eff": f"{round(100 * min(eff)):d}--{round(100 * max(eff)):d}\\%",
     "ch_coh_Q": rng([c["xiQ"] for c in coh]), "ch_coh_W": rng([c["xiW"] for c in coh])}
L = [f"% generated by analyses/chernoff/numbers_chernoff.py from out/podsumowanie_{TAG}.json -- do not edit by hand"]
L += [f"\\expandafter\\def\\csname res@{k}\\endcsname{{{v}}}" for k, v in m.items()]
OUT.write_text("\n".join(L) + "\n"); print(OUT); print("\n".join(L))
